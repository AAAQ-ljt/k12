-- 期望输出：与参考答案真实输出逐字一致（用 CHAR(10) 拼行，避免依赖 sql_mode 的转义行为）
SET @expected := CONCAT(
  '    1', CHAR(10),
  '   2 2', CHAR(10),
  '  3 3 3', CHAR(10),
  ' 4 4 4 4', CHAR(10),
  '5 5 5 5 5');

SET @spec := CONCAT(
  '输出 5 行：第 1 行打印 1 个 1，第 2 行打印 2 个 2 …… 第 5 行打印 5 个 5。', CHAR(10),
  '两点格式要求：', CHAR(10),
  '1. 同一行里的数字之间用一个半角空格隔开；', CHAR(10),
  '2. 每行前面用空格补齐，让金字塔居中（第 1 行补 4 个空格、第 2 行补 3 个…… 第 5 行不补）。', CHAR(10),
  '标点与空格请用英文半角；行尾多余的空格不影响判定。');

SET @example := CONCAT(
  '若题目要求打印 3 行金字塔，正确输出就是下面 3 行（每行左边的空格就是上面说的补齐，数字之间只有一个空格）：', CHAR(10),
  CHAR(10),
  '  1', CHAR(10),
  ' 2 2', CHAR(10),
  '3 3 3', CHAR(10),
  CHAR(10),
  '本题请按同样的格式打印你自己的 5 行金字塔（行数与数字都要对）。');

UPDATE `coding_problem`
SET `judge_type` = 2,
    `expected_output` = @expected,
    `output_spec` = @spec,
    `output_example` = @example,
    `numeric_tolerant` = 0,
    `update_time` = NOW()
WHERE `problem_id` = 'cp-ph-05';
